#!/usr/bin/env python3
"""Bake SIL OFL fonts into alpha atlases embedded in the executable. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from itertools import groupby
root=Path(__file__).resolve().parents[1]
(root/'build').mkdir(exist_ok=True)
parts=['// Generated by tools/bake_fonts.py. Fonts retain their SIL OFL licenses in licenses/.', '#pragma once', '#include <cstdint>', 'namespace nf {', 'struct FontData { int scale,w,h,cellW,cellH,cols,offsetX,lineHeight; const uint8_t* rle; int rleSize; const uint16_t* advances; };']
faces=[]
for scale,size,name in [(1,14,'AlegreyaSans-Medium.ttf'),(2,22,'AlegreyaSans-Medium.ttf'),(3,30,'AlegreyaSans-Medium.ttf'),(5,48,'CinzelDecorative-Bold.ttf')]:
 font=ImageFont.truetype(str(root/'assets/fonts'/name),size)
 glyphs=[chr(i) for i in range(32,127)]
 bounds=[font.getbbox(c) for c in glyphs]
 left=min(b[0] for b in bounds);top=font.getbbox('H')[1]
 cw=max(b[2] for b in bounds)-left+4;ch=max(b[3] for b in bounds)-top+4
 cols=max(1,512//cw);w=cols*cw;h=((len(glyphs)+cols-1)//cols)*ch
 image=Image.new('L',(w,h));draw=ImageDraw.Draw(image)
 for i,c in enumerate(glyphs):draw.text(((i%cols)*cw+2-left,(i//cols)*ch+2-top),c,font=font,fill=255)
 encoded=[]
 for value,run in groupby(image.tobytes()):
  count=sum(1 for _ in run)
  while count: n=min(255,count);encoded.extend((n,value));count-=n
 advances=[round(font.getlength(c)) for c in glyphs]
 parts.append(f'inline constexpr uint8_t FontRle{scale}[] = {{')
 for start in range(0,len(encoded),32):parts.append(','.join(map(str,encoded[start:start+32]))+',')
 parts.extend(['};',f'inline constexpr uint16_t FontAdvance{scale}[] = {{'+','.join(map(str,advances))+'};'])
 faces.append(f'{{{scale},{w},{h},{cw},{ch},{cols},{left-2},{max(size, ch-1)},FontRle{scale},sizeof(FontRle{scale}),FontAdvance{scale}}}')
 image.save(root/'build'/f'font-atlas-{scale}.png')
parts.append('inline constexpr FontData FontFaces[] = {'+','.join(faces)+'};\n}')
(root/'src/font_data.hpp').write_text('\n'.join(parts)+'\n')
print('Baked font atlases:',sum(len(x) for x in parts),'source bytes')
