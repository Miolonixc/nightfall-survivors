#!/usr/bin/env python3
"""Rebuild original code-authored pixel sprites and the embedded indexed atlas.
Usage: python3 tools/bake_sprites.py (Pillow from requirements-fonts.txt).
"""
from pathlib import Path
import importlib.util
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('art',root/'assets/sprites/source.py')
art=importlib.util.module_from_spec(spec);spec.loader.exec_module(art)
sprites=art.build(); cols=8; cell=48; width=cols*cell; height=((len(sprites)+cols-1)//cols)*cell
atlas=Image.new('RGBA',(width,height));palette=[(0,0,0,0)];indices=[]
for i,(name,im) in enumerate(sprites):
    assert im.size==(48,48),name
    atlas.alpha_composite(im,((i%cols)*cell,(i//cols)*cell))
for pixel in atlas.getdata():
    if pixel[3]==0:pixel=(0,0,0,0)
    if pixel not in palette:palette.append(pixel)
    indices.append(palette.index(pixel))
assert len(palette)<=256
rle=[];at=0
while at<len(indices):
    count=1
    while count<255 and at+count<len(indices) and indices[at+count]==indices[at]:count+=1
    rle.extend((count,indices[at]));at+=count
lines=['// Generated by tools/bake_sprites.py; edit assets/sprites/source.py.','#pragma once','#include <cstdint>','namespace nf {',
       f'constexpr int ArtWidth={width}, ArtHeight={height}, ArtCell={cell}, ArtColumns={cols};',
       'enum ArtId { '+', '.join(n for n,_ in sprites)+' };',
       'inline constexpr uint32_t ArtPalette[] = {'+', '.join(hex((a<<24)|(r<<16)|(g<<8)|b)+'u' for r,g,b,a in palette)+'};',
       'struct ArtFrame { int x,y,w,h,ox,oy; };',
       'inline constexpr ArtFrame ArtFrames[] = {']
for i,(_,im) in enumerate(sprites):
    x,y,right,bottom=im.getbbox()
    lines.append(f'{{{i%cols*cell+x},{i//cols*cell+y},{right-x},{bottom-y},{x-24},{y-40}}},')
lines+=['};','inline constexpr uint8_t ArtRle[] = {']
for i in range(0,len(rle),40):lines.append(','.join(map(str,rle[i:i+40]))+',')
lines+=['};','} // namespace nf','']
(root/'src/sprite_data.hpp').write_text('\n'.join(lines))
atlas.save(root/'assets/sprites/atlas.png')
# Labelled 2x preview uses the actual exported atlas pixels.
preview=Image.new('RGB',(8*104,((len(sprites)+7)//8)*120),'#17242e');d=ImageDraw.Draw(preview)
for i,(name,_) in enumerate(sprites):
    x=(i%8)*104;y=(i//8)*120
    tile=atlas.crop(((i%8)*48,(i//8)*48,(i%8+1)*48,(i//8+1)*48)).resize((96,96),Image.Resampling.NEAREST)
    preview.paste(tile,(x,y),tile);d.text((x+2,y+99),name,fill='#d4d8c7')
preview.save(root/'assets/sprites/preview.png')
print(f'{len(sprites)} frames, {len(palette)} colours, {width}x{height} atlas, {len(rle)} RLE bytes')
